#!/usr/bin/env python3
"""
immich-tombstone — stop Immich from re-uploading permanently deleted photos.

Immich keeps no record of intentionally deleted assets (see discussion #4282),
so the mobile app re-uploads any photo that still exists on the phone after it
is purged from the server trash. This script runs from cron and:

Phase 1 (capture): records the SHA1 checksum of every asset in the trash.
Phase 2 (control): finds recently updated active assets whose checksum is on
  the blocklist (= a re-upload) and, depending on `mode` in config.json:

  - "tombstone" (default): archives the asset (visibility=archive) and
    truncates its original file + transcoded video to 0 bytes on disk,
    keeping the generated thumbnails. The checksum stays in the database,
    so the mobile app gets `duplicate` on its pre-upload check and STOPS
    re-uploading forever. The asset remains visible in the Archive view at
    preview quality while using ~0 disk space.
  - "archive": same, but files are left untouched (no filesystem access
    needed; disk space is not reclaimed).
  - "delete": force-deletes the re-upload (the phone will re-upload it
    again on the next backup — infinite loop, kept for completeness).

  If an active asset matches the id recorded on the blocklist:
  - it was a tombstone the user un-archived → the checksum is unblocked and
    the empty husk deleted; the phone re-uploads the full version next backup
  - otherwise the user restored it from the trash → the checksum is unblocked

State files live next to the config file:
  blocklist.tsv   — checksum \t asset_id \t date \t original_file_name
  tombstones.tsv  — asset_id \t timestamp \t original_path
  state.json      — timestamp of the last successful sweep
  tombstone.log   — action log

Usage: immich_tombstone.py [/path/to/config.json]

This code was generated by an AI (Claude). Use at your own risk.
"""
import json
import sys
import urllib.request
from datetime import datetime, timedelta, timezone
from pathlib import Path

CONFIG_PATH = Path(sys.argv[1] if len(sys.argv) > 1 else Path(__file__).resolve().parent / "config.json")
STATE_DIR = CONFIG_PATH.resolve().parent
CONFIG = json.loads(CONFIG_PATH.read_text())

API = CONFIG["api_url"].rstrip("/")
KEY = CONFIG["api_key"]
MODE = CONFIG.get("mode", "tombstone")  # tombstone | archive | delete
NTFY = CONFIG.get("ntfy_url")  # optional
# Where this host sees Immich's UPLOAD_LOCATION (tombstone mode only)
MEDIA_ROOT = Path(CONFIG.get("media_root", "/data"))
# Path prefix the Immich API reports for assets (as mounted inside the container)
MEDIA_PREFIX = CONFIG.get("media_prefix", "/data")

BLOCKLIST = STATE_DIR / "blocklist.tsv"
TOMBSTONES = STATE_DIR / "tombstones.tsv"
STATE = STATE_DIR / "state.json"
LOG = STATE_DIR / "tombstone.log"

if MODE not in ("tombstone", "archive", "delete"):
    sys.exit(f"invalid mode {MODE!r} (expected tombstone, archive or delete)")


def log(msg):
    line = f"{datetime.now().isoformat(timespec='seconds')} {msg}"
    print(line)
    with LOG.open("a") as f:
        f.write(line + "\n")


def api(method, path, body=None):
    req = urllib.request.Request(
        f"{API}{path}",
        data=json.dumps(body).encode() if body is not None else None,
        headers={"x-api-key": KEY, "Content-Type": "application/json"},
        method=method,
    )
    with urllib.request.urlopen(req, timeout=30) as r:
        raw = r.read()
        return json.loads(raw) if raw else None


def search_assets(filters):
    """Paginate POST /api/search/metadata and return all items."""
    items, page = [], 1
    while True:
        d = api("POST", "/api/search/metadata", {**filters, "size": 250, "page": page})
        batch = d["assets"]["items"]
        items.extend(batch)
        next_page = d["assets"].get("nextPage")
        if not next_page:
            break
        page = int(next_page)
    return items


def load_tsv(path, key_field=0, n_fields=4):
    entries = {}
    if path.exists():
        for line in path.read_text().splitlines():
            if line.strip():
                fields = line.split("\t", n_fields - 1)
                entries[fields[key_field]] = tuple(f for i, f in enumerate(fields) if i != key_field)
    return entries


def save_tsv(path, entries):
    tmp = path.with_suffix(".tsv.tmp")
    tmp.write_text(
        "".join(f"{k}\t" + "\t".join(v) + "\n" for k, v in sorted(entries.items()))
    )
    tmp.replace(path)


def local_path(original_path):
    """Map the container path reported by the API to a path on this host."""
    p = original_path
    if p.startswith(MEDIA_PREFIX):
        p = p[len(MEDIA_PREFIX):]
    return MEDIA_ROOT / p.lstrip("/")


def wipe_files(assets):
    """Truncate originals and transcoded videos to 0 bytes (thumbnails are kept).
    assets: dict asset_id -> original_path. Returns bytes freed."""
    freed = 0
    for asset_id, original_path in assets.items():
        targets = []
        p = local_path(original_path)
        if p.is_file():
            targets.append(p)
        # encoded-video/<userId>/<id[0:2]>/<id[2:4]>/<assetId>*.mp4
        targets += [
            f
            for f in (MEDIA_ROOT / "encoded-video").glob(
                f"*/{asset_id[:2]}/{asset_id[2:4]}/{asset_id}*"
            )
            if f.is_file()
        ]
        for f in targets:
            size = f.stat().st_size
            if size:
                f.write_bytes(b"")
                freed += size
    return freed


def notify(msg):
    if not NTFY:
        return
    try:
        urllib.request.urlopen(
            urllib.request.Request(NTFY, data=msg.encode(), method="POST"), timeout=10
        )
    except Exception as e:
        log(f"WARN ntfy: {e}")


def main():
    blocked = load_tsv(BLOCKLIST)  # checksum -> (asset_id, date, name)
    tombs = load_tsv(TOMBSTONES, n_fields=3)  # asset_id -> (timestamp, original_path)
    now = datetime.now(timezone.utc)

    # --- Phase 1: capture checksums of everything in the trash ---
    # v3 silently ignores the isTrashed filter in search/metadata; trashedAfter works
    added = 0
    for a in search_assets({"trashedAfter": "2000-01-01T00:00:00Z"}):
        if a["checksum"] not in blocked:
            blocked[a["checksum"]] = (a["id"], now.date().isoformat(), a["originalFileName"])
            added += 1
            log(f"BLOCKED {a['originalFileName']} ({a['checksum']})")

    # --- Phase 2: hunt re-uploads among recently updated assets ---
    state = json.loads(STATE.read_text()) if STATE.exists() else {}
    since = state.get("last_run")
    # 1-day margin in case a run failed; full sweep when there is no state yet
    filters = {}
    if since:
        margin = datetime.fromisoformat(since) - timedelta(days=1)
        filters["updatedAfter"] = margin.isoformat()

    entombed, deleted, restored, revived = [], [], [], []
    for a in search_assets(filters):
        if a["isTrashed"]:
            continue
        entry = blocked.get(a["checksum"])
        if not entry:
            continue
        if a.get("visibility") == "archive":
            continue  # an existing tombstone (or manual archive) — leave it alone
        if a["id"] == entry[0]:
            if a["id"] in tombs:
                # the user un-archived a tombstone: they want the photo back.
                # Unblock and delete the empty husk; the phone re-uploads the
                # full version on its next backup.
                api("DELETE", "/api/assets", {"ids": [a["id"]], "force": True})
                del tombs[a["id"]]
                del blocked[a["checksum"]]
                revived.append(a["originalFileName"])
                log(f"UNBLOCKED (un-archived) {a['originalFileName']} — the app will re-upload the full version")
            else:
                # same id as when captured: the user restored it from the trash
                del blocked[a["checksum"]]
                restored.append(a["originalFileName"])
                log(f"UNBLOCKED (restored by user) {a['originalFileName']}")
        elif MODE == "delete":
            api("DELETE", "/api/assets", {"ids": [a["id"]], "force": True})
            deleted.append(a["originalFileName"])
            log(f"DELETED re-upload {a['originalFileName']} ({a['checksum']})")
        else:
            # re-upload → tombstone: archive it (the checksum stays in the DB,
            # so the app stops re-uploading) and truncate files in the sweep below
            api("PUT", "/api/assets", {"ids": [a["id"]], "visibility": "archive"})
            tombs[a["id"]] = (now.isoformat(), a["originalPath"])
            blocked[a["checksum"]] = (a["id"], entry[1], entry[2])
            entombed.append(a["originalFileName"])
            log(f"TOMBSTONED {a['originalFileName']} ({a['checksum']})")

    # --- File sweep: tombstones from the last 48h (tombstone mode only) ---
    # (re-truncating covers a video transcode that finished after the last run)
    freed = 0
    if MODE == "tombstone":
        recent = {
            aid: v[1]
            for aid, v in tombs.items()
            if datetime.fromisoformat(v[0]) > now - timedelta(hours=48)
        }
        freed = wipe_files(recent)

    save_tsv(BLOCKLIST, blocked)
    save_tsv(TOMBSTONES, tombs)
    STATE.write_text(json.dumps({"last_run": now.isoformat()}))

    if entombed:
        notify(
            f"Immich: {len(entombed)} re-uploads tombstoned"
            f" ({freed // 1048576} MB freed): {', '.join(entombed[:10])}"
        )
    if deleted:
        notify(f"Immich: {len(deleted)} re-uploads deleted: {', '.join(deleted[:10])}")
    if revived:
        notify(f"Immich: {len(revived)} tombstones un-archived, the app will re-upload them: {', '.join(revived[:10])}")
    log(
        f"OK blocked={len(blocked)} new={added} tombstoned={len(entombed)} deleted={len(deleted)}"
        f" freed={freed // 1048576}MB restored={len(restored)} revived={len(revived)}"
    )


if __name__ == "__main__":
    try:
        main()
    except Exception as e:
        log(f"ERROR {type(e).__name__}: {e}")
        sys.exit(1)
